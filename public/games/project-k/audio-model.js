export const SCHEMA = 'project-k-audio-review/v1';
export const MAX_GAIN = 16;
export function baseline(catalog) {
  return Object.fromEntries(catalog.clips.map(c => [c.id, c.originalGain]));
}
export function validate(catalog, gains) {
  if (!gains || Object.keys(gains).length !== catalog.clips.length) throw Error('Số lượng SFX không khớp catalog.');
  const names = new Map();
  for (const clip of catalog.clips) {
    const gain = gains[clip.id];
    if (typeof gain !== 'number' || !Number.isFinite(gain) || gain < 0 || gain > MAX_GAIN)
      throw Error(`Volume không hợp lệ: ${clip.name} (0–1600%).`);
    if (names.has(clip.name) && names.get(clip.name) !== gain) throw Error(`Các clip cùng tên phải cùng gain: ${clip.name}`);
    names.set(clip.name, gain);
  }
  return gains;
}
export function makeExport(catalog, gains) {
  validate(catalog, gains);
  return {schema: SCHEMA, exportedAt: new Date().toISOString(), sourceFingerprint: catalog.fingerprint,
    sources: catalog.sources, units: 'linear gain: 1 = 100%, 0 = mute; replaces SoundLevels gain, not a multiplier of its previous value',
    instructions: ['Only apply entries whose changed is true. Verify GUID, source hashes and current baseline first.',
      'Keep music, cue volumes, group sliders and master volume unchanged. Never modify the audio waveform.',
      'SoundLevels is generated by SoundBalanceProbe. Add a persistent authored override or update the generating pipeline; do not only hand-edit generated assets.',
      'Runtime SoundLevels.Of is keyed by AudioClip.name: all same-name clips share one gain.',
      'Procedural Guard pulse requires a runtime gain hook in DefenseFeedback; it currently bypasses SoundLevels.',
      'Respect project AGENTS.md. Validate all playback paths in Unity after applying.'],
    clips: catalog.clips.map(c => ({id: c.id, name: c.name, path: c.path, sha256: c.sha256,
      applyMode: c.applyMode, originalGain: c.originalGain, requestedGain: gains[c.id], changed: gains[c.id] !== c.originalGain}))};
}
export function readImport(catalog, file) {
  if (file?.schema !== SCHEMA || file.sourceFingerprint !== catalog.fingerprint)
    throw Error('File sai định dạng hoặc khác phiên bản catalog.');
  if (!Array.isArray(file.clips) || file.clips.length !== catalog.clips.length) throw Error('File thiếu SFX.');
  const originals = new Map(catalog.clips.map(c => [c.id, c]));
  const gains = {};
  for (const row of file.clips) {
    const c = originals.get(row.id);
    if (!c || Object.hasOwn(gains, row.id) || row.name !== c.name || row.path !== c.path ||
        row.sha256 !== c.sha256 || row.originalGain !== c.originalGain || row.applyMode !== c.applyMode)
      throw Error('ID hoặc dữ liệu gốc của SFX bị thay đổi.');
    gains[row.id] = row.requestedGain;
  }
  return validate(catalog, gains);
}
